# The Fibonacci number generator
# This is a much better implementation of the Fibonacci number generator than the direct iterator implementation in generator_fibonacci_example.py

def fibonacci(n):
    p = pp = 1
    for i in range(n):
        if i in [0, 1]:
            yield 1
        else:
            n = p + pp
            pp, p = p, n
            yield n

fibs = list(fibonacci(10))
print(fibs)
